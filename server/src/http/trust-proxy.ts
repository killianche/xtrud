// От кого принимаем X-Forwarded-For. Раньше стояло trustProxy: true — Fastify
// брал самый левый адрес цепочки, а nginx только дописывает к присланному
// заголовку ($proxy_add_x_forwarded_for). Любой клиент подставлял свой
// «X-Forwarded-For: 1.2.3.4» и получал свежий лимит на каждый запрос —
// перебор паролей упирался только в скорость (2026-09-13).
//
// Теперь доверяем лишь адресам, откуда реально приходит nginx: он ходит на
// 127.0.0.1:8100, порт опубликован docker-proxy, и контейнер видит соединение
// от шлюза сети supabase_default (FACT 2026-09-13: remoteAddress 172.18.0.1 в
// логе xtrud-api). Не вся сеть 172.16.0.0/12: соседние контейнеры той же сети
// иначе могли бы подделать заголовок. Loopback — проверки изнутри контейнера.
//
// Fastify идёт по цепочке справа налево, пока адрес доверенный, и берёт
// первый чужой — это $remote_addr, который дописал nginx. Всё, что клиент
// прислал левее, не учитывается.
//
// Если шлюз сменится (сеть пересоздали), req.ip станет адресом шлюза: лимит
// окажется общим на всех — строже, а не слабее. Это сразу видно по 429 и
// правится здесь.
export const TRUSTED_PROXIES: string[] = ["127.0.0.1/32", "::1/128", "172.18.0.1/32"];
