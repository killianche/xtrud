/**
 * Единый источник текста для диалогов блокировки/разблокировки — используется
 * в master/[id].tsx, client/[id].tsx и orders/[id].tsx (см. handleBlock* там).
 * Централизовано, потому что каждое слово здесь должно быть правдой (QA-дефект
 * «интерфейс обещает то, чего не делает»), и три независимые копии одного и
 * того же текста рано или поздно разойдутся.
 *
 * Что реально происходит при блокировке (миграция 0124,
 * supabase/migration-drafts/0124_user_blocking_core.sql):
 *  - RESTRICTIVE-политики на public.orders / public.order_responses прячут
 *    заказы и отклики В ОБЕ СТОРОНЫ на сервере — это гарантировано независимо
 *    от версии клиента.
 *  - Профиль публично читаем по RLS (master_profiles_read_all ... USING(true))
 *    и на сервере НЕ скрывается вообще. Клиент прячет профиль заблокированного
 *    в своём каталоге/избранном/на экране профиля (use-user-blocks.ts,
 *    useBlockedUserIds) — но ТОЛЬКО для того, кто нажал «Заблокировать»:
 *    список id, которых заблокировал текущий пользователь, доступен только
 *    ему по RLS (user_blocks_select_own). Обратное направление — что именно
 *    вижу заблокировавшего меня человека — RLS намеренно не отдаёт (иначе
 *    заблокированный смог бы вычислить, кто его заблокировал), поэтому
 *    симметрично спрятать свой профиль от другой стороны невозможно ни
 *    сейчас, ни в будущей версии приложения без нового серверного объекта.
 *    Текст ниже поэтому не обещает это другой стороне.
 */

export function blockConfirmMessage(name: string): string {
  return (
    `Вы перестанете видеть заказы, отклики и профиль «${name}». Ему станут ` +
    `недоступны ваши заказы и отклики — это гарантирует сервер. Скрыть от ` +
    `него свой профиль мы не можем: иначе он смог бы понять, что именно вы ` +
    `его заблокировали. Если он уже знает ваш номер, звонки и сообщения вне ` +
    `приложения мы остановить не можем. Разблокировать можно в любой момент ` +
    `в настройках.`
  );
}

export function blockSuccessMessage(): string {
  return (
    "Вы больше не увидите его заказы, отклики и профиль. Ему больше не " +
    "доступны ваши заказы и отклики — это гарантирует сервер. Скрыть от " +
    "него свой профиль мы не можем: иначе он смог бы понять, что вы его " +
    "заблокировали."
  );
}
