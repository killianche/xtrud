// Гейт каскадного появления блоков главной v2 (docs/HOME_V2_2026-10.md §5.4).
//
// Анимация должна играть один раз — в момент, когда секция переходит из
// «загрузка» в «есть данные», а НЕ на каждом заходе на таб. При тёплом старте
// (данные уже в кеше React Query) секция рендерится сразу в финальном виде —
// значение здесь фиксируется в момент первого рендера и больше не меняется,
// поэтому тёплый старт (`isLoadingAtMount === false`) никогда не анимируется.

import { useRef } from "react";

/**
 * `isLoadingAtMount` — комбинированный `isLoading` всех персонализированных
 * запросов блока на момент САМОГО ПЕРВОГО рендера. `useRef` фиксирует его
 * один раз: если при первом рендере шла реальная загрузка — каскад разрешён
 * на весь текущий монтаж экрана; если данные были в кеше — каскад не играет
 * никогда в рамках этого монтажа (даже когда isLoading мимолётно true/false).
 */
export function useCascadeReveal(isLoadingAtMount: boolean): boolean {
  return useRef(isLoadingAtMount).current;
}
