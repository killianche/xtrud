/**
 * Без категории человека нет в списке специалистов (DECISION владельца
 * 2026-09-11). То, что относится к каталогу, — показ в «Специалистах» и
 * «Принимаю задания» — до первой категории не включается. Вместо тихо серого
 * переключателя человек видит, что сделать, и одну кнопку туда.
 *
 * Отклики к этому не относятся: откликаться можно и без категории
 * (DECISION владельца 2026-09-11).
 */

import { confirmAsync } from "@/lib/confirm";

export function promptChooseCategory(onChoose: () => void): void {
  void confirmAsync({
    title: "Сначала выберите категорию",
    message:
      "В списке специалистов показываются только те, кто выбрал хотя бы одну категорию. После этого включатся показ в каталоге и «Принимаю задания». Расскажите и о себе — так клиенты выбирают охотнее.",
    confirmText: "Выбрать категории",
    cancelText: "Позже",
  }).then((ok) => {
    if (ok) onChoose();
  });
}
