/**
 * Категория для задания, написанного своими словами (№259, как у YouDo):
 * человек нажал «Далее» — категорию ставим сами, а на форме её видно и
 * можно поменять.
 *
 * Только наверняка (владелец, 2026-10-07, №269: «Переставить столы в кафе»
 * пословный подбор отправил в «Плитку и мозаику» — «всё, что не знает,
 * оставлять без категории»): категория берётся лишь из подсказки-формулировки,
 * где нашлись все слова запроса. Иначе — «Без категории»: на форме строки
 * категории нет, подберёт админ (№251). Пословный подбор и сервер
 * (search_categories) здесь не участвуют — оба угадывают.
 */

import { UNCATEGORIZED_L2_ID } from "@/lib/product-scope";

export function guessCategoryId(
  phraseHits: readonly { l2: string }[],
  visible: ReadonlySet<string>,
): string {
  return phraseHits.find((p) => visible.has(p.l2))?.l2 ?? UNCATEGORIZED_L2_ID;
}
