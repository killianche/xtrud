/**
 * realAvatarUrl — единый источник истины «что считать настоящим фото аватара».
 *
 * Возвращает URL ТОЛЬКО для реально загруженного пользователем фото (Supabase
 * Storage). Любая сгенерированная DiceBear-заглушка (`api.dicebear.com` —
 * shapes / avataaars / initials / любая) и пустое значение → `null`, чтобы UI
 * нарисовал инициалы (см. <Avatar>).
 *
 * Решение 2026-05-23 (владелец): плейсхолдеры аватаров переведены на ИНИЦИАЛЫ.
 * Прежнее правило «аватар-заглушка = DiceBear shapes» отменено — у всех
 * аккаунтов без своего фото (и у новых) теперь кружок с инициалами имени.
 * Демо-аккаунты хранят в БД shapes-ссылку — мы её здесь отбраковываем, поэтому
 * базу править не нужно: фронт сам показывает инициалы.
 *
 * Используется в обоих <Avatar> компонентах и в местах с прямым <Image> для
 * аватара (favorites, master hero).
 */
export function realAvatarUrl(url?: string | null): string | null {
  if (!url) return null;
  // Любая ссылка на DiceBear — это генерёжка-заглушка, а не загруженное фото.
  if (url.includes("api.dicebear.com")) return null;
  return url;
}
