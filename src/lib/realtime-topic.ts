// Уникальное имя канала для подписки на изменения в базе.
//
// Зачем (FACT, разбор падения у пользователя 2026-09-04):
// `supabase.channel(topic)` НЕ создаёт новый канал, если канал с таким именем
// уже зарегистрирован — он возвращает существующий
// (node_modules/@supabase/realtime-js RealtimeClient.channel). А
// `removeChannel` асинхронный: он сначала дожидается unsubscribe и только
// потом убирает канал.
//
// Очистка эффекта в React синхронная и результата не ждёт. Поэтому при
// повторном запуске эффекта — а он случается на обычном пути «человек
// зарегистрировался», когда userId меняется с пустого на настоящий, — новый
// вызов получал СТАРЫЙ, уже подписанный канал. Добавление обработчика к
// подписанному каналу библиотека запрещает и бросает исключение:
//
//   cannot add `postgres_changes` callbacks for realtime:my-responses:… after
//   `subscribe()`
//
// Исключение вылетало из эффекта, его ловил экранный обработчик ошибок — и
// человек видел белый экран «Что-то пошло не так» сразу после регистрации.
//
// Решение: у каждой подписки своё имя канала. Совпасть с живым каналом оно не
// может, поэтому библиотека всегда создаёт новый. Для postgres_changes имя
// канала — просто идентификатор на клиенте, фильтры задаются в `.on()`,
// поэтому суффикс ни на что не влияет.

let counter = 0;

/** Имя канала, которое гарантированно не совпадёт с уже живым. */
export function uniqueRealtimeTopic(prefix: string): string {
  counter += 1;
  return `${prefix}#${Date.now().toString(36)}-${counter.toString(36)}`;
}
