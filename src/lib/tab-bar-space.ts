// Сколько места занимает системное нижнее меню.
//
// ЗАЧЕМ (FACT, 2026-09-05). Владелец прислал скриншот: последняя карточка в
// ленте «Найти задание» проходит сквозь нижнее меню, текст читается прямо
// через панель. Две причины, обе настоящие:
//
//  1. Экраны резервировали место наугад и каждый по-своему: +24, +32, +96,
//     +100. Системное меню на iPhone занимает 49 pt НАД безопасной областью
//     (UITabBar, стандартная высота UIKit). При безопасной области 34 pt меню
//     съедает 83 pt, а лента резервировала 58 — ровно строки текста и не
//     хватало, что и видно на скриншоте.
//  2. На iOS до 26 панель становится прозрачной, когда список докручен до
//     края (поведение UITabBar с iOS 15). На iOS 26 её место занимает Liquid
//     Glass, поэтому владелец видел это только на старом устройстве.
//     Лечится отдельно — параметром disableTransparentOnScrollEdge в
//     app/(tabs)/_layout.tsx.
//
// Здесь — только первая причина: одно число вместо четырёх догадок.
//
// UNKNOWN: высота плавающей панели на iOS 26 системой не опубликована. 64
// взято с запасом относительно классических 49; если на устройстве останется
// лишний зазор, число правится здесь одно на всё приложение.

import { useSafeAreaInsets } from "react-native-safe-area-context";
import { LIQUID_GLASS } from "@/components/ui/GlassSurface";

/** Высота самой панели, без безопасной области. */
export const TAB_BAR_HEIGHT = LIQUID_GLASS ? 64 : 49;

/**
 * Видимая высота панели — для плавающих элементов рядом с ней (кнопка «+»).
 * TAB_BAR_HEIGHT взята с запасом, чтобы контент списка гарантированно не
 * уезжал под панель; для позиционирования кнопки этот запас превращался в
 * лишний зазор (владелец, 2026-09-08: «плюсик высоко, сделай ближе к меню»).
 * Плавающая панель iOS 26 занимает меньше классических 49 pt — 52 с учётом
 * её собственного отступа от края.
 */
export const TAB_BAR_VISUAL_HEIGHT = LIQUID_GLASS ? 52 : 49;

/** Место под плавающим элементом: панель + зазор. */
export function floatingBottom(insetBottom: number, gap: number): number {
  return insetBottom + TAB_BAR_VISUAL_HEIGHT + gap;
}

/**
 * Отступ снизу для содержимого вкладки: панель, безопасная область и немного
 * воздуха, чтобы последняя карточка не липла к меню.
 *
 * Использовать во ВСЕХ списках внутри `(tabs)`. Числа «на глаз» больше не
 * добавляем.
 */
export function useTabBarSpace(extra = 12): number {
  const insets = useSafeAreaInsets();
  return insets.bottom + TAB_BAR_HEIGHT + extra;
}
