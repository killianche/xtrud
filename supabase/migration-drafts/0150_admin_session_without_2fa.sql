-- Вход в админку — только логин и пароль, без второго фактора.
--
-- DECISION владельца 2026-09-03: «убери второй фактор, просто по логину и
-- паролю». Владелец видел экран привязки на своём экране и решение принял
-- осознанно; прежнее требование aal2 из docs/ADMIN_PANEL.md §6 отменяется.
--
-- Цена решения названа прямо, чтобы её не пришлось выяснять потом: пароль
-- администратора становится ЕДИНСТВЕННОЙ преградой к персональным данным
-- всех пользователей и к смене пароля любому аккаунту. Украденный или
-- подобранный пароль даёт всё это целиком. Компенсация — длинный пароль и
-- журнал admin_actions, где остаётся каждое действие.
--
-- Что СОХРАНЯЕТСЯ без изменений:
--   * признак администратора читается из базы, а не из клейма в токене —
--     снятие прав действует мгновенно;
--   * демо-аккаунт администратором быть не может (инвариант 0131);
--   * заблокированный администратор модератором не считается.
--
-- Затрагивает только путь админки: is_admin_session() вызывают функции
-- admin_* и политика чтения журнала. Мобильное приложение её не использует.

BEGIN;

CREATE OR REPLACE FUNCTION public.is_admin_session()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, auth, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1
      FROM public.users u
     WHERE u.id = auth.uid()
       AND u.is_admin
       AND NOT u.is_demo
       AND u.status = 'active'
  );
$$;

-- Незавершённые привязки аутентификатора больше ни на что не влияют, но
-- оставлять половинчатое состояние нельзя: при следующем входе оно сбивало бы
-- с толку. Снимаем все факторы администратора.
DELETE FROM auth.mfa_factors f
 USING public.users u
 WHERE f.user_id = u.id
   AND u.is_admin;

DO $$
DECLARE
  v_src text;
BEGIN
  SELECT prosrc INTO v_src FROM pg_proc WHERE proname = 'is_admin_session';
  IF v_src LIKE '%aal2%' THEN
    RAISE EXCEPTION 'второй фактор всё ещё требуется — правка не применилась';
  END IF;
  RAISE NOTICE 'Вход в админку: логин и пароль, без второго фактора.';
END
$$;

COMMIT;
