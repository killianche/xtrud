-- 0050_cities_add_large_villages.sql
--
-- Добавление 3 крупных «городских центров» Сунженского района РИ в таблицу
-- cities. По населению эти 3 села-«поселения» больше 15K и фактически
-- являются городскими центрами с собственной инфраструктурой:
--
--   - Орджоникидзевская — ~60K (бывшая станица, переименована в Сунжа в 2016)
--   - Серноводская      — ~15K
--   - Нестеровская      — ~17K
--
-- Подход скопирован из проекта Ingush-Business: их `CITIES` const содержит
-- 8 поселений (5 muni-городов + 3 крупных села). У нас раньше эти 3 были
-- спрятаны как villages Сунженского района — после миграции они top-level
-- cities, доступные напрямую в Город picker.
--
-- Идемпотентно: ON CONFLICT (id) DO NOTHING.

INSERT INTO cities (id, name, sort_order) VALUES
  ('ordzhonikidzevskaya', 'Орджоникидзевская', 6),
  ('sernovodskaya', 'Серноводская', 7),
  ('nesterovskaya', 'Нестеровская', 8)
ON CONFLICT (id) DO NOTHING;
