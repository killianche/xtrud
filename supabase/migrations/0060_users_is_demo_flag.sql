-- Migration 0060 — users.is_demo флаг для разметки seed-данных (P0-7).
--
-- Контекст: research/MASTER_ACCOUNT_PLAN.md §P0-7. Сейчас в каталоге
-- мастеров намешаны seed-данные (для демо руководителям и для
-- разработки) с потенциальными настоящими пользователями. Без явного
-- флага невозможно:
--   1. Скрыть seed-данные из публичной выдачи когда зайдут реальные
--      мастера (иначе клиент пишет seed-мастеру → не получает ответа →
--      теряет доверие).
--   2. Показать «Демо» badge в admin-режиме.
--   3. Фильтровать аналитику (профиль views, конверсии) на реальных vs
--      тестовых.
--
-- Что делаем:
--   1. Добавляем users.is_demo bool default false NOT NULL.
--   2. UPDATE is_demo = true для всех текущих мастеров (они ВСЕ seed —
--      пометили UUIDs f0000xxx, известные seed-данные миграций
--      0036, 0038, 0039, 0044, 0054).
--
-- Что НЕ делаем сейчас (для безопасности):
--   - Queries (use-top-masters / use-masters-by-l2 / use-master-public)
--     НЕ меняются — пока показываем всех включая demo. Иначе каталог
--     был бы пустым.
--   - Когда появятся первые настоящие мастера — отдельной задачей
--     добавить фильтр WHERE NOT u.is_demo (или оставить с флагом
--     показа в admin-режиме).

-- ============================================================================
-- COLUMN
-- ============================================================================

ALTER TABLE public.users
  ADD COLUMN is_demo boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.users.is_demo IS
  'true = seed-аккаунт для демонстрации/разработки. По умолчанию false. Заполнено в миграции 0060 для всех существующих master-seed (UUID префикс f00000xxx). Используется для скрытия из публичной выдачи когда придут реальные мастера. На текущей фазе queries фильтр НЕ применяют — UI показывает всех.';

CREATE INDEX users_is_demo_idx ON public.users (is_demo) WHERE is_demo = true;

-- ============================================================================
-- BACKFILL
-- ============================================================================

-- Все мастера сейчас в БД — это seed. UUIDs начинаются с 'f0000'
-- (паттерн миграций 0036/0038/0039/0044/0054).
UPDATE public.users
SET is_demo = true
WHERE is_master = true
  AND id::text LIKE 'f0000%';

-- Также помечаем демо-клиентов (Алина и др.) — они тоже seed.
UPDATE public.users
SET is_demo = true
WHERE is_client = true
  AND id::text LIKE 'f0000%';
