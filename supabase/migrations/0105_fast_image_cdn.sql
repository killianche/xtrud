-- 0105_fast_image_cdn.sql
--
-- Ускорение демо-фотографий. Источник picsum.photos медленный (на каждую
-- картинку 0.3-2.5s, отдаёт тяжёлый JPEG и делает 302-редирект на fastly),
-- из-за чего портфолио мастеров и обложки статей грузятся рывками и пустыми
-- плейсхолдерами. Жалоба пользователя 2026-05-22: «фотографии плохо грузятся
-- все на сайте».
--
-- Решение: проксируем все picsum-ссылки через images.weserv.nl — публичный
-- кэширующий image-CDN. Он:
--   * кэширует результат (picsum/seed/X детерминирован → стабильный кэш-хит),
--   * отдаёт webp (q=70/72) вместо JPEG → ~2x меньше байт,
--   * ограничивает ширину (w) под фактический размер показа.
-- Замер 2026-05-22: weserv webp ~17-33KB / ~1.1-1.4s (cached) против
-- picsum JPEG ~39KB / ~2.5s.
--
-- ВАЖНО: это демо-данные (seed). Реальные фото мастеров и заказов грузятся в
-- Supabase Storage (свой быстрый CDN) и НЕ трогаются этой миграцией. Когда демо
-- заменится на реальный контент, picsum-ссылок не останется и миграция станет
-- no-op.
--
-- Идемпотентность: переписываем только строки, ещё указывающие на
-- picsum.photos. Повторный запуск (или запуск на уже исправленной базе) ничего
-- не делает. Миграция идёт после сид-миграций 0033 (статьи) и 0054 (демо-мастер
-- с портфолио), поэтому на свежей базе тоже поймает вставленные ими ссылки.

update portfolio_items
set url = 'https://images.weserv.nl/?url='
        || replace(url, 'https://', '')
        || '&output=webp&q=70&w=800'
where url like 'https://picsum.photos/%';

update articles
set cover_url = 'https://images.weserv.nl/?url='
             || replace(cover_url, 'https://', '')
             || '&output=webp&q=72&w=1200'
where cover_url like 'https://picsum.photos/%';
