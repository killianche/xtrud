-- 0106_orders_contact_name.sql
-- Необязательное контактное имя на заказе (решение владельца 2026-05-24).
-- Клиент при создании заказа может указать имя (по умолчанию подставляется
-- регистрационное, можно изменить/очистить). Показывается мастеру при
-- просмотре заказа ВМЕСТО кликабельного блока «заказчик» — просто имя.
-- Телефон НЕ храним и НЕ показываем: модель «номер клиента скрыт» не меняется.
-- Колонка nullable + безопасна (ADD COLUMN IF NOT EXISTS), откат = DROP COLUMN.

ALTER TABLE public.orders
  ADD COLUMN IF NOT EXISTS contact_name text
  CHECK (contact_name IS NULL OR length(contact_name) <= 80);

COMMENT ON COLUMN public.orders.contact_name IS
  'Необязательное контактное имя, указанное клиентом при создании заказа (может отличаться от регистрационного). Показывается мастеру при просмотре заказа вместо профиля заказчика. Телефон не храним — модель «номер скрыт» не меняется. Owner 2026-05-24.';
