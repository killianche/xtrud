-- 0107: новый нейтральный статус готовности 'unspecified' («Не указан»).
--
-- Зачем (решение владельца 2026-05-24). Когда срочный статус готовности
-- (today / this_week / next_week) истекал, ночная задача переводила мастера в
-- 'unavailable' — а это штраф в выдаче + значок пропадал. Несправедливо: мастер
-- «наказывался» лишь за то, что не продлил таймер. Теперь истечение ведёт в
-- НЕЙТРАЛЬНЫЙ 'unspecified': значок клиенту не показывается, но штрафа в выдаче
-- нет (обычное место). 'unavailable' остаётся только для ЯВНОГО выбора мастером
-- и получает тяжёлый штраф (в самый низ выдачи).
--
-- ADD VALUE обязан идти ОТДЕЛЬНОЙ миграцией: Postgres запрещает использовать
-- только что добавленное значение enum в той же транзакции. Логика (expire,
-- default, разовый сброс) — в 0108.
ALTER TYPE public.availability_status ADD VALUE IF NOT EXISTS 'unspecified' AFTER 'next_week';
