-- 0109_drop_open_dispute_rpc.sql
--
-- Удаление функционала «Оспорить» (спор). Решение владельца продукта 2026-05-28.
--
-- В продукте (доска объявлений) спор не нужен: стороны решают вопросы сами либо
-- в порядке, предусмотренном законодательством РФ (см. текст пользовательского
-- соглашения, app/legal/terms.tsx). Видимой кнопки «Оспорить» в приложении уже
-- не было; функция open_dispute была единственным способом создать спор.
--
-- Сами поля orders.dispute_opened_by / dispute_reason / disputed_at и значение
-- статуса 'disputed' НЕ удаляем намеренно: 0 записей их используют, но на них
-- ссылаются служебные функции журнала смены статусов (trg_log_order_status_change)
-- и активности заказа. Это безвредные неиспользуемые остатки; их удаление
-- потребовало бы переписывать журнал и нести риск без пользы для продукта.
--
-- Применено к prod через MCP apply_migration (имя drop_open_dispute_rpc).
-- Этот файл — копия в репозитории для источника истины.

DROP FUNCTION IF EXISTS public.open_dispute(uuid, text);
